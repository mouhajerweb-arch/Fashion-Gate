import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const base=process.env.FG_QA_URL||'http://127.0.0.1:9401';
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('[data-fg-consent=reject]').click().catch(()=>{});
await page.screenshot({path:'wordpress/.qa/screenshots/hero-desktop.png'});
console.log('MEDIA',await page.locator('.fg-image').evaluateAll(imgs=>imgs.map(i=>({src:i.src,loaded:i.complete&&i.naturalWidth>0}))));
const edit=await page.locator('#wp-admin-bar-elementor_edit_page a').first().getAttribute('href');
console.log('EDIT_URL',edit);
await page.goto(edit || base+'/wp-admin/',{waitUntil:'domcontentloaded'});
if(!page.url().includes('action=elementor')&&edit) await page.goto(edit,{waitUntil:'domcontentloaded'});
await page.waitForTimeout(8000);
console.log('EDITOR_TITLE',await page.title());
console.log('EDITOR_TEXT',(await page.locator('body').innerText()).slice(0,2500));
console.log('FRAMES',page.frames().map(f=>f.url()));
await page.screenshot({path:'wordpress/.qa/screenshots/editor.png'});
await page.goto(base+'/wp-admin/admin.php?page=mlang',{waitUntil:'domcontentloaded'});
console.log('LANG_FORM',await page.locator('input,select').evaluateAll(es=>es.map(e=>({name:e.name,id:e.id,type:e.type,value:e.type==='hidden'?'[hidden]':e.value}))));
await browser.close();
